import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const source=fs.readFileSync(new URL('../lib/homework-priority.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {studentHomeworkList}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const now='2026-11-03T12:00:00Z';
const make=(id,dueAt,extra={})=>({id,startsAt:'2026-11-01T00:00:00Z',dueAt,...extra});
const items=[make('sent','2026-11-01T00:00:00Z'),make('later','2026-11-06T00:00:00Z'),make('soon','2026-11-04T00:00:00Z'),make('late','2026-11-02T00:00:00Z'),make('reopened','2026-11-05T00:00:00Z',{resubmitGrantId:'grant'}),make('future','2026-11-09T00:00:00Z',{startsAt:'2026-11-08T00:00:00Z'})];
const submissions=[{homeworkId:'sent'},{homeworkId:'sent'},{homeworkId:'reopened'}];
const before=JSON.stringify({items,submissions});
const ids=filter=>studentHomeworkList(items,submissions,filter,now).map(item=>item.id);
assert.deepEqual(ids('todo'),['reopened','late','soon','later','future']);
assert.deepEqual(ids('submitted'),['sent']);
assert.deepEqual(ids('all'),['reopened','late','soon','later','future','sent']);
assert.equal(JSON.stringify({items,submissions}),before);
assert.deepEqual(studentHomeworkList([],[],'todo',now),[]);
assert.deepEqual(studentHomeworkList([items[0]],submissions,'todo',now),[]);
console.log('Homework priority: 6 cases passed (reopened, overdue, due order, submitted, immutability, empty).');
